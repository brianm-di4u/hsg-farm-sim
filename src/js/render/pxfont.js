const glyph = (ch) => G[ch] || G[ch.toUpperCase()] || G['?'];
export const PX_FONT_H = 7;
export function pxTextWidth(text) { let w = 0; for (const ch of text) w += glyph(ch)[0].length + 1; return Math.max(0, w - 1); }
// Draws `text` with its top-left at (x, y), in whole pixels, `scale` px per font pixel.
export function pxText(ctx, text, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  x = Math.round(x); y = Math.round(y);
  for (const ch of text) {
    const g = glyph(ch);
    for (let r = 0; r < 7; r++) for (let c = 0; c < g[r].length; c++) if (g[r][c] === '#') ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
    x += (g[0].length + 1) * scale;
  }
}
// A code-made canvas with the text and a 1-px dark outline around every glyph pixel (readable on any ground).
const labels = new Map();
export function pxLabel(text, color = '#ffffff', outline = '#141010') {
  const k = `${text}|${color}|${outline}`;
  let c = labels.get(k);
  if (c) return c;
  c = document.createElement('canvas'); c.width = pxTextWidth(text) + 2; c.height = PX_FONT_H + 2;
  const g = c.getContext('2d');
  for (const [dx, dy] of [[0, 1], [2, 1], [1, 0], [1, 2]]) pxText(g, text, dx, dy, outline);
  pxText(g, text, 1, 1, color);
  labels.set(k, c);
  return c;
}

