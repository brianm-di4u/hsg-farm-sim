// Inline the vendored OFL fonts (vendor/fonts/*.woff2, from npm @fontsource/* 5.2.5) into assets/fonts.css as
// data URIs. Chrome blocks @font-face url() loads from file://, so the fonts travel inside the stylesheet,
// which the build inlines into index.html.  Run: node tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(GAME, 'vendor', 'fonts');
const FACES = [
  ['IM Fell English', 400, 'im-fell-english-latin-400-normal.woff2'],   // 1807, 1871 display
  ['Playfair Display', 700, 'playfair-display-latin-700-normal.woff2'], // 1886 display
  ['Josefin Sans', 700, 'josefin-sans-latin-700-normal.woff2'],         // 1931 display
  ['Righteous', 400, 'righteous-latin-400-normal.woff2'],               // 1955 display
  ['Outfit', 600, 'outfit-latin-600-normal.woff2'],                     // 2026 display
  ['Alegreya', 400, 'alegreya-latin-400-normal.woff2'],                 // body, 1807–1886
  ['Alegreya', 700, 'alegreya-latin-700-normal.woff2'],
  ['Nunito Sans', 400, 'nunito-sans-latin-400-normal.woff2'],           // body, 1931–2026
  ['Nunito Sans', 700, 'nunito-sans-latin-700-normal.woff2'],
];
let css = '/* Generated by tools/build-fonts.mjs from vendor/fonts (SIL Open Font License 1.1). Do not edit. */\n';
for (const [family, weight, file] of FACES) {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;` +
    `src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.mkdirSync(path.join(GAME, 'assets'), { recursive: true });
fs.writeFileSync(path.join(GAME, 'assets', 'fonts.css'), css);
console.log('assets/fonts.css', (css.length / 1024).toFixed(1), 'KB');
